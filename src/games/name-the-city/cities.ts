export const QUIZ_LENGTHS = [10, 20] as const;
export type QuizLength = (typeof QUIZ_LENGTHS)[number];

/** Pick `count` distinct random cities from a difficulty's pool. */
export function pickCities(difficulty: Difficulty, count: number): City[] {
  const pool = [...CITY_POOLS[difficulty]];
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, count);
}
