export type City = {
  id: string;
  name: string;
  country: string;
  lat: number;
  lon: number;
  /** Other spellings and names that count as correct. */
  alt: string[];
};

function c(
  name: string,
  country: string,
  lat: number,
  lon: number,
  ...alt: string[]
): City {
  const id = `${name}-${country}`
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  return { id, name, country, lat, lon, alt };
}

