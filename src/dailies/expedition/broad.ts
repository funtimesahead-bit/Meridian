import { normalize } from "@/games/name-the-city/match";
import type { Answer, Prompt } from "./prompts";

/* Broad prompts with long answer lists, beyond countries and cities.

   Each answer is one line:   Name | other name | other name = weight
   Weight is how readily people think of it: about 10 for the obvious ones,
   1 for the obscure. Lines without "= n" get 2.

   Lists are curated, so only answers written here are accepted. Common
   wording is added automatically: "Mount Fuji" also accepts "Fuji",
   "Danube River" accepts "Danube", "Sahara Desert" accepts "Sahara". */

const PREFIXES = ["mount ", "mt ", "mt. ", "lake ", "the ", "river ", "isla ", "isle of "];
const SUFFIXES = [
  " river",
  " desert",
  " mountains",
  " range",
  " sea",
  " national park",
  " islands",
  " island",
  " volcano",
];

/** A name plus the shorter forms people commonly type. Also used on what players type. */
export function variants(name: string): string[] {
  const out = new Set([name]);
  let changed = true;
  while (changed) {
    changed = false;
    for (const form of [...out]) {
      const lower = form.toLowerCase();
      for (const p of PREFIXES) {
        if (lower.startsWith(p) && form.length > p.length + 2) {
          const next = form.slice(p.length);
          if (!out.has(next)) {
            out.add(next);
            changed = true;
          }
        }
      }
      for (const s of SUFFIXES) {
        if (lower.endsWith(s) && form.length > s.length + 2) {
          const next = form.slice(0, -s.length);
          if (!out.has(next)) {
            out.add(next);
            changed = true;
          }
        }
      }
    }
  }
  return [...out];
}

function parse(lines: string): Answer[] {
  const answers: Answer[] = [];
  const seen = new Set<string>();
  for (const raw of lines.split("\n")) {
    const line = raw.trim();
    if (!line) continue;
    const [namesPart, weightPart] = line.split("=");
    const names = namesPart.split("|").map((n) => n.trim()).filter(Boolean);
    const id = normalize(names[0]);
    if (!id || seen.has(id)) continue;
    seen.add(id);
    answers.push({
      id,
      name: names[0],
      keys: [...new Set(names.flatMap(variants).map(normalize).filter(Boolean))],
      weight: weightPart ? Number(weightPart.trim()) || 2 : 2,
    });
  }
  return answers;
}

function prompt(id: string, text: string, group: string | undefined, lines: string): Prompt {
  return { id, text, kind: "list", group, answers: parse(lines) };
}

